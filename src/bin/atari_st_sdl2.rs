//! Minimal SDL2 frontend for the emulated Atari ST — video + keyboard + sound.
//!
//! Demo/test binary, separate from the `rust68` library (see the Cargo
//! `sdl2-frontend` feature): it exists to visually and interactively verify
//! the correct operation of the emulation (CPU + ST peripherals), not to be
//! a "complete" ST emulator (no GUI configuration, no state save, no
//! persistent-write floppy support).
//!
//! Usage: `atari_st_sdl2 [--model <name>] <rom.img> [disk.stx|disk.msa|disk.st]`
//!
//! `--model` selects a machine profile from the
//! `systems::atari_st::model` lexicon (RAM, Blitter presence — see its doc
//! for the list and what is actually taken into account). The loaded TOS is
//! independent of the model: its version is auto-detected from its header
//! (`os_version`) to choose the right ROM base, not from `--model`.
//!
//! ## Architectural choices
//! - No dedicated real-time timer: this crate provides none (see
//!   `AtariSt::tick`, purely accounting-based). The real-time pace is
//!   obtained by throttling on the fill level of the SDL2 audio queue
//!   (`AudioQueue`) — the rate at which the host audio driver consumes this
//!   queue IS the real-time reference clock.
//! - Sound is generated by sampling `Ym2149::channel_level` at the
//!   `cycles_per_sample` rate derived from the CPU clock (8 MHz) and the
//!   target sample rate, independently of the CPU execution step (which
//!   varies per instruction).
//! - The keyboard translates SDL2 `Scancode`s into ST scancodes (a fixed
//!   table derived from the publicly documented PC-XT layout, which the
//!   ST's HD6301 keyboard controller largely reuses): make code as-is
//!   (bit 7 = 0), break code = make code | 0x80.
//! - The mouse is injected through the same serial channel as the keyboard:
//!   on a real ST, the IKBD controller (HD6301) handles the keyboard AND
//!   the mouse/joystick together and sends both through the keyboard ACIA.
//!   A relative mouse movement is a publicly documented 3-byte packet
//!   (IKBD protocol): header `0xF8 | left | (right << 1)`, then signed
//!   dX and dY, one byte each. The delta is computed by us from the
//!   absolute position of each `MouseMotion` event (not SDL2's native
//!   relative mouse mode, whose cursor warp turned out to generate spurious
//!   synthetic events depending on the platform/backend): the host cursor
//!   therefore remains visible, in addition to the one drawn by GEM.

