const AUDIO_SAMPLE_RATE: i32 = 44_100;
/// Bytes per output sample: stereo (2 channels) x i16 (2 bytes)
/// — see `desired_spec`.
const AUDIO_BYTES_PER_SAMPLE: u32 = 4;
/// Audio queue fill threshold (in bytes) above which the emulation is
/// slowed down to stay at real-time pace.
///
/// Deliberately generous (~500 ms, rather than the ~250 ms of a previous
/// version): the wall-clock pacing (see below, where this threshold is only
/// a secondary safety net) remains vulnerable to an occasional `sleep` that
/// runs much longer than requested — macOS timer coalescing, the app being
/// put to sleep, or simple OS preemption — which can drain a good part of
/// the queue at once; a wider margin absorbs this kind of episode without
/// an audible glitch rather than hoping to eliminate it at the source
/// (beyond the reach of a plain `std::thread::sleep`).
const AUDIO_QUEUE_HIGH_WATERMARK: u32 = AUDIO_SAMPLE_RATE as u32 * AUDIO_BYTES_PER_SAMPLE / 2; // ~500 ms
/// Initial fill threshold (in bytes) before starting playback — without
/// this margin, the queue starts empty and the host audio device consumes
/// faster than we can produce during the very first frames (and on every
/// subsequent brief emulation stall, since previously only a HIGH threshold
/// existed, with no cushion against underrun): every time the queue empties
/// completely, SDL2 replays silence or loops the last block depending on
/// the backend, heard as a "glitch"/click — hence the delayed playback
/// start here.
const AUDIO_QUEUE_PRIME_WATERMARK: u32 = AUDIO_SAMPLE_RATE as u32 * AUDIO_BYTES_PER_SAMPLE / 5; // ~200 ms
/// Microwire gain smoothing coefficient (see its doc in `main`) — a time
/// constant of about 1/coeff samples, ~4-5 ms at 44100 Hz: fast enough to
/// track a genuine intended volume change, slow enough to avoid an audible
/// jump in the middle of a non-zero signal.
const GAIN_SMOOTH_COEFF: f32 = 0.005;
/// Default model if `--model` is not specified.
const DEFAULT_MODEL: &str = "1040ste";

fn usage(program: &str) -> ! {
    eprintln!(
        "Usage: {program} [--model <name>] [--ntsc] <rom.img> [disk.stx|disk.msa|disk.st]\n\n\
         Available models (--model, case-insensitive): 520st, 1040st, megast, \
         520ste, 1040ste (default), megaste — see `systems::atari_st::model` for the \
         details of each profile (RAM, Blitter...).\n\
         --ntsc: 60 Hz video mode (263 lines/frame) instead of the default PAL 50 Hz \
         (313 lines/frame) — see `peripherals::atari_st::glue::VideoMode`."
    );
    std::process::exit(1);
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let program = args[0].clone();

    let mut model_name = DEFAULT_MODEL.to_string();
    let mut ntsc = false;
    let mut positional: Vec<&String> = Vec::new();
    let mut iter = args.iter().skip(1);
    while let Some(arg) = iter.next() {
        if arg == "--model" {
            match iter.next() {
                Some(v) => model_name = v.clone(),
                None => usage(&program),
            }
        } else if arg == "--ntsc" {
            ntsc = true;
        } else {
            positional.push(arg);
        }
    }
    if positional.is_empty() {
        usage(&program);
    }
    let rom_path = positional[0];
    let disk_path = positional.get(1);

    let model = rust68::systems::atari_st::model::AtariModel::parse(&model_name)
        .unwrap_or_else(|| {
            eprintln!("Unknown model: {model_name}");
            usage(&program);
        });
    let profile = model.profile();
    eprintln!(
        "Model: {} (RAM {} KB, Blitter {})",
        profile.name,
        profile.ram_size / 1024,
        if profile.has_blitter { "present" } else { "absent" }
    );

    let rom = std::fs::read(rom_path).unwrap_or_else(|e| {
        eprintln!("Unable to read ROM {rom_path}: {e}");
        std::process::exit(1);
    });

    if rom.len() < 4 {
        eprintln!("ROM too short to contain a TOS header (os_version)");
        std::process::exit(1);
    }
    // `os_version` (BCD) is at offset 2 of the TOS header, publicly
    // documented (e.g. 0x0162 for TOS 1.62): TOS >= 1.06 is mapped to
    // 0xE00000 on a real ST/STE, TOS <= 1.04 to 0xFC0000 (see `set_rom_base`).
    // Independent of the machine model (--model): any compatible TOS
    // can be flashed into a given real machine.
    let os_version = u16::from_be_bytes(rom[2..4].try_into().unwrap());
    let rom_base = if os_version >= 0x0106 {
        0x00E0_0000
    } else {
        rust68::systems::atari_st::DEFAULT_ROM_BASE
    };

    let ram_size = profile.ram_size;
    let mut st = AtariSt::from_model(profile, rom);
    st.set_rom_base(rom_base);
    if ntsc {
        st.set_video_mode(rust68::peripherals::atari_st::glue::VideoMode::Ntsc60);
        eprintln!("Video mode: NTSC 60 Hz (--ntsc)");
    }
    if let Some(path) = disk_path {
        match load_floppy(path) {
            Ok(disk) => st.floppy_a = Some(disk),
            Err(e) => eprintln!("Unable to load disk {path}: {e} (starting without a floppy disk)"),
        }
    }

    // `RUST68_CARTRIDGE_HGH`/`RUST68_CARTRIDGE_LOW`: two separate 8-bit ROM
    // images (high byte / low byte of each word — the common EPROM format
    // of ST/STE hardware diagnostic cartridges), interleaved here into a
    // single native 16-bit image and mapped to the cartridge port (`$FA0000`).
    if let (Ok(hgh_path), Ok(low_path)) = (
        std::env::var("RUST68_CARTRIDGE_HGH"),
        std::env::var("RUST68_CARTRIDGE_LOW"),
    ) {
        match (std::fs::read(&hgh_path), std::fs::read(&low_path)) {
            (Ok(hgh), Ok(low)) if hgh.len() == low.len() => {
                let mut cart = Vec::with_capacity(hgh.len() * 2);
                for (h, l) in hgh.iter().zip(low.iter()) {
                    cart.push(*h);
                    cart.push(*l);
                }
                eprintln!("Cartridge loaded: {} bytes ({hgh_path} + {low_path})", cart.len());
                st.load_cartridge(cart);
            }
            (Ok(hgh), Ok(low)) => {
                eprintln!(
                    "HGH ({}) and LOW ({}) sizes differ, cartridge not loaded",
                    hgh.len(),
                    low.len()
                );
            }
            (hgh_res, low_res) => {
                if let Err(e) = hgh_res {
                    eprintln!("Unable to read {hgh_path}: {e}");
                }
                if let Err(e) = low_res {
                    eprintln!("Unable to read {low_path}: {e}");
                }
            }
        }
    }

    // On a cold boot, TOS performs installed-RAM detection by deliberately
    // triggering bus errors beyond the actual size (restarting via the ROM
    // overlay on each failure) — an algorithm that is precise and notoriously
    // tricky to reproduce identically (even established emulators put
    // dedicated effort into it). Since we already know the allocated RAM
    // size, we pre-fill the warmstart "cookie" system variables (addresses
    // publicly documented in any TOS reference: `memvalid`/`memval2`/
    // `memval3`/`phystop`) so that TOS takes the "warm restart" path
    // directly and skips this detection.
    //
    // `RUST68_COLD_BOOT=1` disables this shortcut (real cold boot, slower)
    // — useful to check whether a display issue comes from initialization
    // normally done during a cold boot (palette, desktop config...) that the
    // "warm restart" path assumes is already done and skips.
    if std::env::var("RUST68_COLD_BOOT").is_err() {
        st.write32(0x420, 0x752019F3); // memvalid
        st.write32(0x43A, 0x237698AA); // memval2
        st.write32(0x51A, 0x5555AAAA); // memval3
        st.write32(0x42E, ram_size as u32); // phystop
        // IKBD Timer-C gate ($0EE4, RAM): TOS normally initializes it to
        // 0x1111 during its own IKBD setup (A5=0). The Timer C handler
        // (200 Hz) does `ASL.W #3,($0EE4).L` and then skips processing of
        // pending IKBD bytes if the result is positive or zero (BPL taken)
        // — with 0x1111, ASL.W #3 = 0x8888 (bit 15 = 1, N set, BPL not
        // taken, bytes properly processed). The "warm restart" shortcut
        // above skips exactly the TOS code that normally sets this value,
        // and RAM starts at zero (`AtariSt::new`) — without this
        // pre-fill, 0x0000 would give ASL.W #3 = 0x0000 (N=0, BPL taken),
        // leaving this IKBD processing path inactive until TOS goes through
        // it itself. Identified via the companion project Stay (same
        // pre-fill, same bytes).
        st.write8(0x0EE4, 0x11);
        st.write8(0x0EE5, 0x11);
    }

    let mut cpu = Cpu::new();
    cpu.reset(&mut st);

    if std::env::var("RUST68_COLD_BOOT").is_err() && !st.has_cartridge() {
        // MEMORY_CONF ($FF8001): same shortcut as memvalid/phystop above —
        // except that TOS itself UNCONDITIONALLY writes MEMORY_CONF=0 very
        // early during boot (even before consulting memvalid), normally
        // corrected only at the very end of the RAM detection algorithm
        // that this shortcut precisely skips. A simple pre-fill would
        // therefore get overwritten immediately: `pin_memory_conf` pins the
        // value so it survives this write (see its doc). Done AFTER
        // `cpu.reset()`, not before: disabling the ROM overlay at address 0
        // before reading the reset vector (SSP/PC) would make it read from
        // still-blank RAM instead of ROM.
        //
        // Skipped if a cartridge is loaded (see the doc of `has_cartridge`):
        // it performs its own RAM detection by freely writing this same
        // register, which pinning it would break.
        if let Some(conf) = AtariSt::expected_memory_conf(ram_size) {
            st.pin_memory_conf(conf);
        }
    }

    // `RUST68_TRACE_ALL=1`: logs EVERY real bus transaction (CPU and
    // Blitter — see `RamBus` in `systems::atari_st`, not covered by this
    // since the Blitter accesses memory via its own bus, not the CPU's) at
    // its exact size (.B/.W/.L), with the calling instruction's address and
    // a component label — see `rust68::trace::FileTraceSink` for the
    // filtering environment variables (essential: without
    // `RUST68_TRACE_ALL_MIN`/`_MAX`, a full interactive session generates
    // gigabytes).
    let ram_len = st.ram().len();
    let rom_len = st.rom_len();
    let blitter_present = st.blitter_present();
    let mut trace_sink = FileTraceSink::from_env(Box::new(move |addr: u32| {
        AtariSt::describe_addr_static(ram_len, rom_base, rom_len, blitter_present, addr)
    }));
    let trace_cpu_wanted = trace_sink.as_ref().map(|s| s.wants_cpu_trace()).unwrap_or(false);

    let sdl_context = sdl2::init().expect("init SDL2");
    let video_subsystem = sdl_context.video().expect("init video subsystem");
    let audio_subsystem = sdl_context.audio().expect("init audio subsystem");

    // Window/texture sized from the current resolution AND its border
    // ([`BorderLayout`]), at an integer scale — not a fixed 640x400 size
    // stretched afterward, which made GEM text unreadable once the border
    // was added (non-integer scale factor). Recreated on the fly in the
    // main loop if the resolution changes along the way (see
    // `current_texture_size` below).
    let mut current_layout = BorderLayout::for_resolution(st.shifter.resolution());
    let (win_w, win_h) = current_layout.window_size();

    let window = video_subsystem
        .window("Rust68 — Atari ST", win_w, win_h)
        .position_centered()
        .build()
        .expect("window creation");
    let mut canvas = window.into_canvas().build().expect("canvas creation");
    let texture_creator = canvas.texture_creator();
    let mut texture = texture_creator
        .create_texture_streaming(PixelFormatEnum::RGB24, win_w, win_h)
        .expect("texture creation");
    // Fixed logical size (independent of the actual window size): SDL2
    // then scales itself with letterboxing (black bars) rather than
    // stretching non-uniformly — essential in fullscreen (Ctrl+Shift+F10,
    // see below), where the actual window size (that of the screen) has no
    // reason to share the aspect ratio computed by `BorderLayout`.
    let _ = canvas.set_logical_size(win_w, win_h);

    // Mouse exclusive to the window as long as it has focus: confined to
    // the window (`set_grab`) and the host cursor hidden (GEM draws its
    // own). Deliberately NOT SDL2's "relative" mode (`set_relative_mouse_mode`)
    // — see the comment on `last_mouse_pos` below: its internal warp-based
    // recentering already caused a diagonal drift on this backend: the
    // existing absolute-position delta computation remains unchanged, only
    // the confinement/cursor display change here.
    // `RUST68_NO_MOUSE_GRAB=1` disables all of this (debug/automation): the
    // confinement gets in the way of external absolute positioning (e.g.
    // `cliclick` from an automation tool, which can no longer move the host
    // cursor out of the window to then reposition it elsewhere).
    let mouse_grab_enabled = std::env::var("RUST68_NO_MOUSE_GRAB").is_err();
    if mouse_grab_enabled {
        canvas.window_mut().set_grab(true);
        sdl_context.mouse().show_cursor(false);
    }

    let desired_spec = AudioSpecDesired {
        freq: Some(AUDIO_SAMPLE_RATE),
        // Stereo (not mono): DMA sound (STE) has real independent left/
        // right channels (see `DmaSound::next_sample`), with independent
        // left/right volumes driven by the Microwire/LMC1992 (see
        // `Microwire::left_gain`/`right_gain`) — the STE factory diagnostic
        // cartridge (the "Stereo 1 kHz/500 Hz tones" test) specifically
        // relies on this to produce 2 tones at distinct volumes. Merging
        // them into a single mono channel, as before, made this distinction
        // impossible to hear.
        channels: Some(2),
        samples: Some(1024),
    };
    let audio_queue: AudioQueue<i16> = audio_subsystem
        .open_queue(None, &desired_spec)
        .expect("audio queue open");
    // Playback started only once `AUDIO_QUEUE_PRIME_WATERMARK` is reached
    // (see its doc) — no `resume()` here.
    let mut audio_started = false;
    let mut drive_sound = load_drive_sound(AUDIO_SAMPLE_RATE as u32);

    let mut event_pump = sdl_context.event_pump().expect("event pump");
    let mut mouse_left = false;
    let mut mouse_right = false;
    // Delta computed by us from the absolute position (`x`/`y` of the
    // event), rather than relying on `xrel`/`yrel` in SDL2's relative mouse
    // mode: that mode continuously recenters the host cursor via a warp,
    // and depending on the platform/backend (notably `sdl2-compat`, a
    // compatibility layer on top of SDL3, not original SDL2) this warp can
    // itself generate a synthetic motion event — observed in practice: a
    // continuous diagonal drift instead of tracking the mouse. `None` as
    // long as no position has been seen yet, so as not to send a huge
    // initial delta from an arbitrary origin.
    let mut last_mouse_pos: Option<(i32, i32)> = None;
    // The window always displays 640x400 (see `render_frame`), but the
    // logical ST resolution can be smaller (320x200 in low resolution): a
    // movement in WINDOW pixels must be scaled to LOGICAL ST pixels before
    // being sent to the IKBD, otherwise the mouse moves 2x faster on the ST
    // side than what the window visually shows — the GEM cursor reaches
    // (and overshoots) the edge of the screen well before the host cursor
    // actually gets there. The fractional remainder (`mouse_scale_carry`)
    // is carried over from one event to the next so small slow movements
    // aren't lost to repeated truncation.
    let mut mouse_scale_carry = (0.0f64, 0.0f64);
    // Accumulated mouse movement (in logical ST pixels, after scaling)
    // since the last sampling — injected into the IKBD once per frame
    // rather than immediately on every raw SDL event, as the real IKBD
    // firmware does (sampling at the VBL rate, see
    // `Machine::flush_input_vbl`/`IKBD_VBL()` from Steem SSE in the
    // companion project Stay). Sending one packet per SDL event —
    // potentially much more frequent than the real ~50 Hz — could
    // desynchronize GEM cursor tracking relative to the real hardware.
    let mut mouse_dx_acc = 0i32;
    let mut mouse_dy_acc = 0i32;

    // `profile.cpu_hz`: see its doc in `model.rs` — informative only for
    // now (all profiles return 8 MHz), but it is already the single source
    // of truth for this computation rather than a separate constant that
    // could diverge the day an accelerated CPU mode gets modeled.
    let cycles_per_sample = profile.cpu_hz as f64 / AUDIO_SAMPLE_RATE as f64;
    let mut audio_cycle_acc = 0.0f64;
    let mut audio_buffer: Vec<i16> = Vec::with_capacity(2048);
    // DC blocker (one-pole high-pass filter) on the final mix, left/right
    // separately: our PSG mixing (`mix_sample`) centers the total level of
    // the 3 channels on a fixed constant rather than on the signal's real
    // (rolling) average, which leaves a continuous bias (DC) whenever a
    // number of active channels different from the theoretical average is
    // playing — visible as a line at 0 Hz on the spectrum, and audible as a
    // "pop" every time a tone starts/stops. A standard DC blocker removes
    // this bias dynamically, whatever its exact cause, rather than trying
    // to find a perfect centering constant (impossible: the right value
    // depends on the number of channels active at that precise instant,
    // not on a global constant).
    let mut dc_blocker_left = DcBlocker::new();
    let mut dc_blocker_right = DcBlocker::new();
    // Smoothed gain (not applied as-is to every sample): the Microwire can
    // change volume AT ANY MOMENT of the signal, including in the middle
    // of a non-zero tone period — an instantaneous gain jump at that
    // precise instant produces an audible discontinuity (a "click"), even
    // if the target volume itself is correct. This is a well-known digital
    // volume control artifact ("zipper noise"): the real LMC1992 (analog
    // silicon) itself has a certain transition time constant, so smoothing
    // here is more faithful than an instantaneous jump, not just an ad-hoc
    // fix. Initialized to the REAL starting gain (not 0) so as not to
    // produce its own startup click by ramping up from silence.
    let mut gain_smooth_left = st.microwire.left_gain();
    let mut gain_smooth_right = st.microwire.right_gain();
    // `RUST68_RECORD_WAV=path.wav`: records as-is (after the DC filter and
    // mixing, before `mute`) the 16-bit stereo stream sent to the audio
    // queue — to inspect the spectrum of the sound actually produced.
    let mut wav_recorder = std::env::var("RUST68_RECORD_WAV").ok().map(|path| {
        WavRecorder::create(&path).unwrap_or_else(|e| panic!("RUST68_RECORD_WAV={path} creation: {e}"))
    });

    // `RUST68_DEBUG=1`: prints a progress point (steps executed, PC, SR)
    // once per second on stderr — useful to check that the emulation is
    // progressing without being stuck, without instrumenting every
    // instruction during normal use.
    let debug = std::env::var("RUST68_DEBUG").is_ok();
    // `RUST68_DUMP_VIDEO=1` (with `RUST68_DEBUG=1`): hex dump of the first
    // 14 lines of video RAM starting from `video_base`, once per second —
    // to inspect the actual content during a visually observed display
    // corruption (independent of the keyboard: triggers automatically, no
    // need to send a key to the SDL2 window at the right moment).
    let dump_video = std::env::var("RUST68_DUMP_VIDEO").is_ok();
    // `RUST68_TRACE_STEPS=N`: traces pc/sr/opcode of the first N CPU steps
    // (one-off diagnostic, e.g. to observe cold-boot RAM detection
    // instruction by instruction).
    let trace_steps: u64 = std::env::var("RUST68_TRACE_STEPS")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(0);
    let trace_stride: u64 = std::env::var("RUST68_TRACE_STRIDE")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(1);
    // `RUST68_WATCH_VIDEO=1`: monitors the video RAM area for lines 11-66
    // (where the display corruption was observed) and logs the PC of the
    // instruction that just modified it, the first time its content
    // changes — to identify the responsible TOS instruction without having
    // to manually compare before/after dumps.
    let watch_video = std::env::var("RUST68_WATCH_VIDEO").is_ok();
    let mut watch_video_hash: Option<u64> = None;
    let mut watch_video_hits: u32 = 0;
    let mut watch_video_last_cycles: u64 = 0;
    let mut step_count: u64 = 0;
    let mut last_report = std::time::Instant::now();
    let last_report_start = std::time::Instant::now();

    // `RUST68_WATCH_RANGE=start,end` (hex, e.g. "0fb900,0fc900"): monitors
    // BYTE BY BYTE (not just a global hash) a precise video RAM area, and
    // logs pc/address/before/after for EVERY modified byte — to pinpoint
    // exactly which instruction writes what, and when, into content
    // already in place before a "tint" blit (hop=1) is applied on top of
    // it (diagnostic for the "Visualisation" dropdown menu).
    let watch_range: Option<(u32, u32)> = std::env::var("RUST68_WATCH_RANGE").ok().and_then(|s| {
        let (a, b) = s.split_once(',')?;
        Some((
            u32::from_str_radix(a.trim(), 16).ok()?,
            u32::from_str_radix(b.trim(), 16).ok()?,
        ))
    });
    let mut watch_range_snapshot: Vec<u8> = Vec::new();
    if let Some((start, end)) = watch_range {
        watch_range_snapshot = (start..end).map(|a| st.read8(a)).collect();
    }
    let mut watch_range_hits: u64 = 0;

    // `RUST68_TRACE_FILL=1`: on every entry into the software rectangle-fill
    // routine ($E12C40, identified via RUST68_WATCH_VIDEO as responsible
    // for the menu corruption), dumps the complete register state + the 2
    // words at the top of the stack (probable return address if entered via
    // JSR/BSR) — to compare against a reference run (Hatari) at the same
    // entry point.
    let trace_fill = std::env::var("RUST68_TRACE_FILL").is_ok();
    const TRACE_FILL_PCS: [u32; 4] = [0xE12C40, 0xE12C4E, 0xE12C56, 0xE12C62];
    let mut trace_fill_hits: [u32; TRACE_FILL_PCS.len()] = [0; TRACE_FILL_PCS.len()];
    const TRACE_FILL_MAX_HITS_EACH: u32 = 6;

    // `RUST68_TRACE_BLITDET=1`: traces the Blitter hardware-detection
    // routine ($E01062, identified by disassembling the TOS ROM) —
    // deliberate probe for a bus error on TST.W $FFFF8A00 (Blitter
    // halftone register 0). Logs the entry (a0=0 expected) and the exit
    // (D0=2 if Blitter detected, D0=0 otherwise) to check whether Rust68
    // mistakenly triggers a real bus error where the real silicon would not.
    let trace_blitdet = std::env::var("RUST68_TRACE_BLITDET").is_ok();
    let mut blitdet_hits: u32 = 0;

    // `RUST68_TRACE_DISPATCH=1`: traces the `jmp (a5)` at $E0B4AA that
    // chooses, via a function pointer read at $9A(A4), between the
    // hardware Blitter routine ($E0B4AC) and the software fallback
    // ($E12C1C) — logs A4, the pointer read at $9A(A4) (i.e. A5 just
    // before the jmp), and D4/D6/A0 to see whether the pointer itself or
    // the upstream parameters are corrupted.
    let trace_dispatch = std::env::var("RUST68_TRACE_DISPATCH").is_ok();
    let mut dispatch_hits: u32 = 0;

    // `RUST68_TRACE_SIM=1`: captures the complete state at the entry of a
    // call ($E12C1C, before any register mutation by the routine), then
    // at its exit (RTS at $E12C4C/$E12C7C/$E12C92) dumps the bytes actually
    // written to video RAM starting from the original A1 — to replay the
    // algorithm by hand (Python) and compare against the real result,
    // without depending on a Hatari reference.
    let trace_sim = std::env::var("RUST68_TRACE_SIM").is_ok();
    // `RUST68_TRACE_CURSOR=1`: dumps the complete state on every execution
    // of $E1366C (writing a word of the cursor sprite — see disassembly in
    // ETAT.md), to compare register by register between a "clean" position
    // (far from the menu) and a "corrupted" position (near the menu / icon
    // click).
    let trace_cursor = std::env::var("RUST68_TRACE_CURSOR").is_ok();
    // `RUST68_TRACE_BLIT_CALLER=1`: at the entry of the cursor-blit trigger
    // routine ($E0B160, TOS 1.62), logs the return address (top of stack)
    // and D7 (future Y_COUNT, before the conditional computation) to trace
    // back to the caller that supplies this parameter.
    let trace_blit_caller = std::env::var("RUST68_TRACE_BLIT_CALLER").is_ok();
    let mut blit_caller_hits: u32 = 0;
    let mut cursor_hits: u32 = 0;
    // `RUST68_TRACE_CA6A=1`: on EVERY entry into the "software skew" loop
    // ($E0CA6A, OR/AND/NOT/XOR dispatch with bit-by-bit shifting, pure CPU
    // implementation — see the "Visualisation" menu investigation), logs
    // the return address (top of stack, only on the very first pass of
    // each call — a1 still at its starting value) as well as a1 (current
    // destination) to identify the caller and correlate with the affected
    // memory area.
    let trace_ca6a = std::env::var("RUST68_TRACE_CA6A").is_ok();
    let mut ca6a_hits: u32 = 0;
    let mut ca6a_last_ret: u32 = 0;
    // Step-by-step (instruction by instruction) trace of the software
    // blitter "skew" routine (0xE0CA6A/0xE0CAB8), armed only on the first
    // call, to observe d6 (shift amount), the source words read via (a0)+,
    // and the combined result actually produced at execution.
    let trace_ca6a_steps = std::env::var("RUST68_TRACE_CA6A_STEPS").is_ok();
    let mut ca6a_step_budget: u32 = 0;
    let mut ca6a_step_armed = false;
    // Traces entry into the text/pattern-drawing dispatcher at 0xE0E480
    // (8-entry jump table indexed via d6/d7, feeding 0xE0E4B6/0xE0E4E6):
    // these two routines execute half as often on STE as on ST when
    // opening the same menu — goal: see whether the input registers
    // already differ at this point.
    let trace_e480 = std::env::var("RUST68_TRACE_E480").is_ok();
    let mut e480_hits: u32 = 0;
    // Traces the pattern-fill routine (TOS 1.62, 0xE10B54-0xE10CA8) at its
    // three Blitter trigger points (TAS.B of the "standard pattern via
    // table", "standard pattern via direct copy", and "custom pattern /
    // variable width" branches): goal, find out in WHICH caller (return
    // address) and with what object parameters (a2) the hop=1 x=8 y=9 call
    // responsible for the checkerboard fill observed in place of the menu
    // text originates — correlated within the SAME run as the complete
    // Blitter parameter trace, to avoid the methodological pitfall of
    // comparing two separate runs (mouse position slightly varies pixel
    // alignment from one manual launch to another).
    let trace_fillpat = std::env::var("RUST68_TRACE_FILLPAT").is_ok();
    let mut fillpat_hits: u32 = 0;
    // `RUST68_TRACE_IKBD_READER=1`: logs the PC + SR of the instruction
    // that just read ACIA_KEYBOARD_DATA (RDRF dropped during this step) —
    // unlike `RUST68_TRACE_IKBD` (bus-side, knows WHAT was read but not WHO
    // read it), this lets us verify that it is indeed the TOS keyboard/
    // mouse interrupt handler consuming the IKBD bytes, and not an
    // unrelated wait loop (SR indicates the current IPL level and the S
    // bit: inside a genuine MFP interrupt handler, IPL must be 6 and S=1).
    let trace_ikbd_reader = std::env::var("RUST68_TRACE_IKBD_READER").is_ok();
    let mut ikbd_reader_hits: u32 = 0;
    // `RUST68_TRACE_IKBD_DISPATCH=1`: logs the target of the `jsr (a2)` at
    // $E03DC4 (end of assembling an IKBD packet, TOS 1.62) — the handler
    // specific to the packet type (mouse/joystick/keyboard) that receives
    // the assembled packet in `a0` — to find out where processing of a
    // complete mouse packet continues.
    let trace_ikbd_dispatch = std::env::var("RUST68_TRACE_IKBD_DISPATCH").is_ok();
    // `RUST68_MUTE=1`: cuts audio output (video debugging without the
    // spurious noise from STE/DMA sound — a separate bug, not yet
    // investigated).
    let mute = std::env::var("RUST68_MUTE").is_ok();
    let mut ikbd_dispatch_hits: u32 = 0;
    let mut sim_entry: Option<([u32; 8], [u32; 8])> = None;
    let mut sim_hits: u32 = 0;
    let mut frame_count_dbg: u32 = 0;

    'running: loop {
        for event in event_pump.poll_iter() {
            match event {
                Event::Quit { .. } => break 'running,
                // Cmd+Shift+F10: manual toggle of mouse exclusivity without
                // losing window focus (temporarily get the real cursor
                // back, e.g. to switch applications). Intercepted before
                // the general forwarding of keys to the IKBD below: must
                // never reach the ST keyboard.
                Event::KeyDown {
                    scancode: Some(Scancode::F10),
                    keymod,
                    repeat: false,
                    ..
                } if mouse_grab_enabled
                    && keymod.intersects(Mod::LGUIMOD | Mod::RGUIMOD)
                    && keymod.intersects(Mod::LSHIFTMOD | Mod::RSHIFTMOD) =>
                {
                    let now_grabbed = !canvas.window().grab();
                    canvas.window_mut().set_grab(now_grabbed);
                    sdl_context.mouse().show_cursor(!now_grabbed);
                    if debug {
                        eprintln!("[mouse] exclusivity toggled -> {now_grabbed}");
                    }
                }
                // Ctrl+Shift+F10: toggle fullscreen ("desktop" mode, no
                // screen-resolution change). Deliberately distinct
                // combination from Cmd+Shift+F10 above (Ctrl, not Cmd/GUI)
                // — no possible conflict between the two shortcuts.
                // Intercepted before the general forwarding of keys to the
                // IKBD: must never reach the ST keyboard.
                Event::KeyDown {
                    scancode: Some(Scancode::F10),
                    keymod,
                    repeat: false,
                    ..
                } if keymod.intersects(Mod::LCTRLMOD | Mod::RCTRLMOD)
                    && keymod.intersects(Mod::LSHIFTMOD | Mod::RSHIFTMOD) =>
                {
                    let target = if canvas.window().fullscreen_state() == FullscreenType::Off {
                        FullscreenType::Desktop
                    } else {
                        FullscreenType::Off
                    };
                    match canvas.window_mut().set_fullscreen(target) {
                        Ok(()) => {
                            if debug {
                                eprintln!("[fullscreen] toggled -> {target:?}");
                            }
                        }
                        Err(e) => eprintln!("[fullscreen] toggle failed: {e}"),
                    }
                }
                Event::Window { win_event: WindowEvent::FocusGained, .. } if mouse_grab_enabled => {
                    canvas.window_mut().set_grab(true);
                    sdl_context.mouse().show_cursor(false);
                }
                Event::Window { win_event: WindowEvent::FocusLost, .. } if mouse_grab_enabled => {
                    canvas.window_mut().set_grab(false);
                    sdl_context.mouse().show_cursor(true);
                }
                // `RUST68_RAM_DUMP_KEY=1`: F2 writes a raw snapshot of all
                // installed RAM to `RUST68_RAM_DUMP_PATH` — to later replay
                // a `RUST68_TRACE_BLITTER` trace from a complete, real RAM
                // state, without the prohibitive overhead of
                // `RUST68_WATCH_RANGE` over all of RAM (which makes boot
                // too slow to be interactive).
                Event::KeyDown {
                    scancode: Some(Scancode::F2),
                    repeat: false,
                    ..
                } if std::env::var("RUST68_RAM_DUMP_KEY").is_ok() => {
                    if let Ok(path) = std::env::var("RUST68_RAM_DUMP_PATH") {
                        match std::fs::write(&path, st.ram()) {
                            Ok(()) => eprintln!("[ram] snapshot ({} bytes) written to {path}", st.ram().len()),
                            Err(e) => eprintln!("[ram] failed to write snapshot: {e}"),
                        }
                    }
                }
                // `RUST68_FB_DUMP_KEY=1`: F3 writes `st.framebuffer` (already
                // computed by `Shifter::render_scanline`, before it goes
                // through the SDL2 texture at all) as raw PPM to
                // `RUST68_FB_DUMP_PATH` — to directly compare what our
                // engine computes internally against a reference
                // reconstruction, without depending on SDL2 display itself.
                Event::KeyDown {
                    scancode: Some(Scancode::F3),
                    repeat: false,
                    ..
                } if std::env::var("RUST68_FB_DUMP_KEY").is_ok() => {
                    if let Ok(path) = std::env::var("RUST68_FB_DUMP_PATH") {
                        let h = st.framebuffer.len();
                        let w = st.framebuffer.first().map(|r| r.len()).unwrap_or(0);
                        let mut out = format!("P6\n{w} {h}\n255\n").into_bytes();
                        for row in &st.framebuffer {
                            for &(r, g, b) in row {
                                out.push(r);
                                out.push(g);
                                out.push(b);
                            }
                        }
                        match std::fs::write(&path, &out) {
                            Ok(()) => eprintln!("[fb] snapshot ({w}x{h}) written to {path}"),
                            Err(e) => eprintln!("[fb] failed to write snapshot: {e}"),
                        }
                    }
                }
                Event::KeyDown {
                    scancode: Some(sc),
                    repeat: false,
                    ..
                } => {
                    if let Some(code) = st_scancode(sc) {
                        st.ikbd.key_make(code);
                    }
                }
                Event::KeyUp {
                    scancode: Some(sc), ..
                } => {
                    if let Some(code) = st_scancode(sc) {
                        st.ikbd.key_break(code);
                    }
                }
                Event::MouseMotion { x, y, .. } => {
                    if debug {
                        eprintln!("[mouse] motion event received x={x} y={y} last_mouse_pos={last_mouse_pos:?}");
                    }
                    if let Some((last_x, last_y)) = last_mouse_pos {
                        // Host window -> logical ST pixels: divide by the
                        // same integer zoom factor as `render_frame`
                        // ([`BorderLayout`]) — the border and logical
                        // resolution units coincide (see its doc), so this
                        // factor alone is enough to convert a window pixel
                        // delta into a logical pixel delta, whether the
                        // movement crosses the border or the active image.
                        let layout = BorderLayout::for_resolution(st.shifter.resolution());
                        let raw_dx =
                            (x - last_x) as f64 / layout.zoom_x as f64 + mouse_scale_carry.0;
                        let raw_dy =
                            (y - last_y) as f64 / layout.zoom_y as f64 + mouse_scale_carry.1;
                        let dx = raw_dx.trunc();
                        let dy = raw_dy.trunc();
                        mouse_scale_carry = (raw_dx - dx, raw_dy - dy);
                        mouse_dx_acc += dx as i32;
                        mouse_dy_acc += dy as i32;
                    }
                    last_mouse_pos = Some((x, y));

                    // Recentering when the host cursor approaches a window
                    // edge: confined by `set_grab` (see above), it would
                    // otherwise end up hitting this physical edge and be
                    // unable to produce any further delta in that direction
                    // — observed symptom: the ST cursor stays stuck at the
                    // right until you go all the way left to "regain room"
                    // (the window acting like a mouse pad too small, with
                    // no way to lift the mouse and set it down further
                    // away). Recentering before reaching the edge gives an
                    // infinite range, like a real relative mouse that gets
                    // lifted. `last_mouse_pos` is updated HERE, synchronously
                    // with the `warp_mouse_in_window` call, NOT by waiting
                    // for the synthetic `MouseMotion` event that this warp
                    // will generate: the latter will arrive with a position
                    // already equal to `last_mouse_pos`, hence a delta of
                    // zero by construction — unlike SDL2's native relative
                    // mode (`set_relative_mouse_mode`, deliberately avoided,
                    // see above) whose internal delta computation
                    // (xrel/yrel) turned out to produce small non-zero
                    // residuals on this backend. Disabled with
                    // `RUST68_NO_MOUSE_GRAB`: a warp would get in the way of
                    // external absolute positioning (`cliclick` etc.) just
                    // as much as confinement itself, already disabled in
                    // that case.
                    if mouse_grab_enabled {
                        let (win_w, win_h) = canvas.window().size();
                        const EDGE_MARGIN: i32 = 4;
                        let near_edge = x < EDGE_MARGIN
                            || y < EDGE_MARGIN
                            || x > win_w as i32 - EDGE_MARGIN
                            || y > win_h as i32 - EDGE_MARGIN;
                        if near_edge {
                            let (cx, cy) = (win_w as i32 / 2, win_h as i32 / 2);
                            sdl_context.mouse().warp_mouse_in_window(canvas.window(), cx, cy);
                            last_mouse_pos = Some((cx, cy));
                        }
                    }
                }
                Event::MouseButtonDown { mouse_btn, .. } => {
                    match mouse_btn {
                        sdl2::mouse::MouseButton::Left => mouse_left = true,
                        sdl2::mouse::MouseButton::Right => mouse_right = true,
                        _ => {}
                    }
                    if debug {
                        eprintln!("[mouse] down {mouse_btn:?} -> left={mouse_left} right={mouse_right}");
                    }
                }
                Event::MouseButtonUp { mouse_btn, .. } => {
                    match mouse_btn {
                        sdl2::mouse::MouseButton::Left => mouse_left = false,
                        sdl2::mouse::MouseButton::Right => mouse_right = false,
                        _ => {}
                    }
                    if debug {
                        eprintln!("[mouse] up {mouse_btn:?} -> left={mouse_left} right={mouse_right}");
                    }
                }
                _ => {}
            }
        }

        // A single mouse sampling per frame (see the doc of
        // `mouse_dx_acc`): injects the movement accumulated since the last
        // frame, regardless of the number of raw SDL events received in
        // the meantime.
        queue_mouse_move(&mut st.ikbd, mouse_dx_acc, mouse_dy_acc, mouse_left, mouse_right);
        mouse_dx_acc = 0;
        mouse_dy_acc = 0;

        // Runs the CPU until a complete video frame has elapsed (detected
        // via the GLUE's frame counter), sampling audio along the way.
        let frame_before = st.glue.frame_count();
        loop {
            if step_count < trace_steps && step_count % trace_stride == 0 {
                eprintln!(
                    "[trace] step={step_count} pc={:#08x} sr={:#06x} opcode={:#06x} a7={:#08x} ssp={:#08x}",
                    cpu.pc,
                    cpu.sr,
                    (st.read8(cpu.pc) as u16) << 8 | st.read8(cpu.pc.wrapping_add(1)) as u16,
                    cpu.a[7],
                    cpu.ssp
                );
            }
            let pc_before = cpu.pc;

            if trace_blitdet && blitdet_hits < 4 && pc_before == 0xE0108A {
                blitdet_hits += 1;
                eprintln!(
                    "[blitdet] hit #{blitdet_hits} pc={pc_before:#08x} d0={:#010x} (2=blitter detected, 0=absent/bus-error) sr={:#06x}",
                    cpu.d[0], cpu.sr
                );
            }

            if trace_dispatch && dispatch_hits < 20 && pc_before == 0xE0B4AA {
                dispatch_hits += 1;
                eprintln!(
                    "[dispatch] hit #{dispatch_hits} pc={pc_before:#08x} a4={:#010x} a5(jmp target)={:#010x} d4={:#010x} d6={:#010x} a0={:#010x} d0={:#010x}",
                    cpu.a[4], cpu.a[5], cpu.d[4], cpu.d[6], cpu.a[0], cpu.d[0]
                );
            }

            if trace_sim && sim_hits < 200 {
                if pc_before == 0xE12C1C && sim_entry.is_none() {
                    sim_entry = Some((cpu.d, cpu.a));
                } else if sim_entry.is_some()
                    && (pc_before == 0xE12C4C || pc_before == 0xE12C7C || pc_before == 0xE12C92)
                {
                    let (entry_d, entry_a) = sim_entry.take().unwrap();
                    sim_hits += 1;
                    let a1_orig = entry_a[1];
                    let bytes: Vec<u8> = (0..64u32)
                        .map(|o| st.read8(a1_orig.wrapping_add(o)))
                        .collect();
                    if bytes.iter().any(|&b| b != 0) {
                        eprintln!(
                            "[sim] #{sim_hits} entry_d={:x?} entry_a={:x?} exit_pc={pc_before:#08x} a1_origin={a1_orig:#010x} bytes={}",
                            entry_d, entry_a,
                            bytes.iter().map(|b| format!("{b:02x}")).collect::<Vec<_>>().join("")
                        );
                    }
                }
            }

            if trace_fill {
                if let Some(idx) = TRACE_FILL_PCS.iter().position(|&p| p == pc_before) {
                    if trace_fill_hits[idx] < TRACE_FILL_MAX_HITS_EACH {
                        trace_fill_hits[idx] += 1;
                        let sp = cpu.a[7];
                        let ret_word0 = st.read16(sp);
                        let ret_word1 = st.read16(sp.wrapping_add(2));
                        let video_base = st.shifter.video_base();
                        eprintln!(
                            "[fill] hit #{} pc={pc_before:#08x} video_base={video_base:#010x} d0={:#010x} d1={:#010x} d2={:#010x} d3={:#010x} d4={:#010x} d5={:#010x} d6={:#010x} d7={:#010x} a0={:#010x} a1={:#010x} a2={:#010x} a3={:#010x} a4={:#010x} a5={:#010x} a6={:#010x} a7={sp:#010x} sr={:#06x} stack[a7..a7+4]={ret_word0:#06x}{ret_word1:04x}",
                            trace_fill_hits[idx],
                            cpu.d[0], cpu.d[1], cpu.d[2], cpu.d[3], cpu.d[4], cpu.d[5], cpu.d[6], cpu.d[7],
                            cpu.a[0], cpu.a[1], cpu.a[2], cpu.a[3], cpu.a[4], cpu.a[5], cpu.a[6],
                            cpu.sr,
                        );
                    }
                }
            }

            if trace_ikbd_dispatch && ikbd_dispatch_hits < 20 && pc_before == 0xE03DC4 {
                ikbd_dispatch_hits += 1;
                let a0 = cpu.a[0];
                let bytes: Vec<u8> = (0..4).map(|o| st.read8(a0.wrapping_add(o))).collect();
                eprintln!(
                    "[ikbd-dispatch] hit #{ikbd_dispatch_hits} target=jsr(a2)={:#010x} a0(packet)={a0:#010x} bytes={}",
                    cpu.a[2],
                    bytes.iter().map(|b| format!("{b:02x}")).collect::<Vec<_>>().join(" ")
                );
            }
            if trace_ikbd_dispatch && ikbd_dispatch_hits < 20 && pc_before == 0xE10CAA {
                let read32 = |st: &mut rust68::systems::atari_st::AtariSt, a: u32| {
                    ((st.read8(a) as u32) << 24)
                        | ((st.read8(a + 1) as u32) << 16)
                        | ((st.read8(a + 2) as u32) << 8)
                        | st.read8(a + 3) as u32
                };
                eprintln!(
                    "[ikbd-hooks] button_vector($2AE2)={:#010x} position_vector($2AEA)={:#010x} notify_vector($2AE6)={:#010x} current_pos($28C2)={:#010x}",
                    read32(&mut st, 0x2AE2),
                    read32(&mut st, 0x2AEA),
                    read32(&mut st, 0x2AE6),
                    read32(&mut st, 0x28C2),
                );
            }

            if trace_blit_caller
                && blit_caller_hits < 300
                && matches!(pc_before, 0xE0B1B2 | 0xE0B518 | 0xE10C02)
            {
                blit_caller_hits += 1;
                let sp = cpu.a[7];
                let ret_addr = st.read32(sp);
                use rust68::peripherals::atari_st::blitter::reg as blitreg;
                let y_count = ((st.blitter.read(blitreg::Y_COUNT) as u16) << 8)
                    | st.blitter.read(blitreg::Y_COUNT1) as u16;
                let x_count = ((st.blitter.read(blitreg::X_COUNT) as u16) << 8)
                    | st.blitter.read(blitreg::X_COUNT1) as u16;
                eprintln!(
                    "[blit-caller] hit #{blit_caller_hits} pc={pc_before:#08x} return={ret_addr:#010x} X_COUNT={x_count} Y_COUNT={y_count} d0={:#010x} d1={:#010x} d2={:#010x} d3={:#010x} d4={:#010x} d6={:#010x} d7={:#010x} a4={:#010x}",
                    cpu.d[0], cpu.d[1], cpu.d[2], cpu.d[3], cpu.d[4], cpu.d[6], cpu.d[7], cpu.a[4],
                );
            }

            if trace_e480 && e480_hits < 500 && pc_before == 0xE0E480 {
                e480_hits += 1;
                let sp = cpu.a[7];
                let ret_addr = st.read32(sp);
                let a1 = cpu.a[1];
                let before: Vec<String> = (0..8).map(|o| format!("{:02x}", st.read8(a1.wrapping_add(o)))).collect();
                eprintln!(
                    "[e480] call #{e480_hits} return={ret_addr:#010x} a4={:#010x} a1={:#010x} d2={:#010x} d3={:#010x} d4={:#010x} d6={:#010x} d7={:#010x} before(a1..+8)={}",
                    cpu.a[4], cpu.a[1], cpu.d[2], cpu.d[3], cpu.d[4], cpu.d[6], cpu.d[7], before.join(" "),
                );
            }

            if trace_fillpat
                && fillpat_hits < 500
                && matches!(pc_before, 0xE10C04 | 0xE10C44 | 0xE10C94)
            {
                fillpat_hits += 1;
                let sp = cpu.a[7];
                // On the first pass over this TAS.B, the return address of
                // the SHARED routine (e10b54-e10ca8) is at the top of the
                // stack; the caller of THIS routine (the one we're really
                // interested in, to find out WHO requested this fill) is
                // at the next level.
                let ret_addr = st.read32(sp);
                let a2 = cpu.a[2];
                let obj_bytes: Vec<u32> = (0..4).map(|i| st.read16(a2.wrapping_add(i * 2)) as u32).collect();
                use rust68::peripherals::atari_st::blitter::reg as blitreg;
                let hop = st.blitter.read(blitreg::HOP);
                let op = st.blitter.read(blitreg::OP);
                let x_count = ((st.blitter.read(blitreg::X_COUNT) as u16) << 8)
                    | st.blitter.read(blitreg::X_COUNT1) as u16;
                let y_count = ((st.blitter.read(blitreg::Y_COUNT) as u16) << 8)
                    | st.blitter.read(blitreg::Y_COUNT1) as u16;
                let long = |a: u32| {
                    ((st.blitter.read(a) as u32) << 24)
                        | ((st.blitter.read(a + 1) as u32) << 16)
                        | ((st.blitter.read(a + 2) as u32) << 8)
                        | st.blitter.read(a + 3) as u32
                };
                let dst_addr = long(blitreg::DST_ADDR);
                let dst_x_inc = ((st.blitter.read(blitreg::DST_X_INC) as u16) << 8)
                    | st.blitter.read(blitreg::DST_X_INC1) as u16;
                let dst_y_inc = ((st.blitter.read(blitreg::DST_Y_INC) as u16) << 8)
                    | st.blitter.read(blitreg::DST_Y_INC1) as u16;
                eprintln!(
                    "[fillpat] hit #{fillpat_hits} branch={pc_before:#08x} shared_routine_return={ret_addr:#010x} hop={hop} op={op:#04x} x={x_count} y={y_count} dst_addr={dst_addr:#010x} dst_xinc={dst_x_inc:#06x} dst_yinc={dst_y_inc:#06x} a2={a2:#010x} d3={:#010x} d4={:#010x} d5={:#010x} d6={:#010x} d7={:#010x}",
                    cpu.d[3], cpu.d[4], cpu.d[5], cpu.d[6], cpu.d[7],
                );
                let _ = obj_bytes;
            }

            if trace_ca6a && ca6a_hits < 500 && pc_before == 0xE0CA6A {
                let sp = cpu.a[7];
                let ret_addr = st.read32(sp);
                if ret_addr != ca6a_last_ret {
                    ca6a_last_ret = ret_addr;
                    ca6a_hits += 1;
                    eprintln!(
                        "[ca6a] call #{ca6a_hits} return={ret_addr:#010x} a1(dst)={:#010x} a2={:#010x} a3(mode)={:#010x} d3={:#010x} d4(stride)={:#010x} d5(count-1)={:#010x} d6(skew)={:#010x} a0(src)={:#010x}",
                        cpu.a[1], cpu.a[2], cpu.a[3], cpu.d[3], cpu.d[4], cpu.d[5], cpu.d[6], cpu.a[0],
                    );
                    eprintln!(
                        "[ca6a-video] resolution={:?} video_base={:#010x}",
                        st.shifter.resolution(),
                        st.shifter.video_base(),
                    );
                    let table_base = cpu.a[0] & !1u32;
                    let words: Vec<String> = (0..16)
                        .map(|i| format!("{:04x}", st.read16(table_base.wrapping_add(i * 2))))
                        .collect();
                    eprintln!(
                        "[ca6a-table] base={table_base:#010x} 16 words = {}",
                        words.join(" ")
                    );
                    if trace_ca6a_steps && !ca6a_step_armed {
                        ca6a_step_armed = true;
                        ca6a_step_budget = 400;
                    }
                }
            }

            if trace_cursor && cursor_hits < 200_000 && pc_before == 0xE1366C {
                let a5 = cpu.a[5];
                let read16 = |st: &mut rust68::systems::atari_st::AtariSt, a: u32| st.read16(a);
                let video_base = st.shifter.video_base();
                let a1 = cpu.a[1];
                let row = if a1 >= video_base { (a1 - video_base) / 160 } else { u32::MAX };
                // Only logs writes near or within the menu bar (lines
                // 0-14) — the thousands of others (cursor elsewhere on the
                // desktop) would drown out the signal.
                if row <= 14 {
                cursor_hits += 1;
                eprintln!(
                    "[cursor] hit #{cursor_hits} a1(dest)={a1:#010x} fb_line={row} d0={:#010x} d1={:#010x} d2={:#010x} d3={:#010x} a0={:#010x} shift(-24,a5)={:#06x} d2src(-20,a5)={:#06x} nwords(-12,a5)={:#06x} src_stride(-c,a5)={:#06x} dst_stride(-e,a5)={:#06x} op1(-26,a5)={:#06x} op2(-2a,a5)={:#06x} op3(-28,a5)={:#06x} op4(-2c,a5)={:#06x}",
                    cpu.d[0], cpu.d[1], cpu.d[2], cpu.d[3], cpu.a[0],
                    read16(&mut st, a5.wrapping_sub(0x24)),
                    read16(&mut st, a5.wrapping_sub(0x20)),
                    read16(&mut st, a5.wrapping_sub(0x12)),
                    read16(&mut st, a5.wrapping_sub(0x0c)),
                    read16(&mut st, a5.wrapping_sub(0x0e)),
                    read16(&mut st, a5.wrapping_sub(0x26)),
                    read16(&mut st, a5.wrapping_sub(0x2a)),
                    read16(&mut st, a5.wrapping_sub(0x28)),
                    read16(&mut st, a5.wrapping_sub(0x2c)),
                );
                }
            }

            let rdrf_before = trace_ikbd_reader
                && ikbd_reader_hits < 40
                && st.acia_keyboard.read(rust68::peripherals::atari_st::acia::reg::CONTROL_STATUS) & 0x01 != 0;

            st.last_pc = cpu.pc;
            if let Some(sink) = trace_sink.as_mut() {
                if trace_cpu_wanted {
                    sink.cpu_step(cpu.pc);
                }
                sink.maybe_break(&cpu);
            }
            let sink_ref: Option<&mut dyn TraceSink> =
                trace_sink.as_mut().map(|s| s as &mut dyn TraceSink);
            let mut tracing_bus = TracingBus {
                inner: &mut st,
                sink: sink_ref,
                pc: cpu.pc,
            };
            let cycles = match cpu.step(&mut tracing_bus) {
                Ok(cycles) => cycles,
                Err(e) => {
                    eprintln!("CPU error, stopping: {e:?} pc={:#08x}", cpu.pc);
                    break 'running;
                }
            };

            if ca6a_step_budget > 0 {
                ca6a_step_budget -= 1;
                eprintln!(
                    "[ca6a-step] pc={pc_before:#010x} -> {:#010x} d0={:#010x} d1={:#010x} d2={:#010x} d3={:#010x} d4={:#010x} d5={:#010x} d6={:#010x} a0={:#010x} a1={:#010x} a2={:#010x}",
                    cpu.pc, cpu.d[0], cpu.d[1], cpu.d[2], cpu.d[3], cpu.d[4], cpu.d[5], cpu.d[6], cpu.a[0], cpu.a[1], cpu.a[2],
                );
                if ca6a_step_budget == 0 {
                    ca6a_step_armed = false;
                }
            }

            if rdrf_before {
                let rdrf_after = st.acia_keyboard.read(rust68::peripherals::atari_st::acia::reg::CONTROL_STATUS) & 0x01 != 0;
                if !rdrf_after {
                    ikbd_reader_hits += 1;
                    let ipl = (cpu.sr >> 8) & 0x07;
                    let supervisor = cpu.sr & 0x2000 != 0;
                    eprintln!(
                        "[ikbd-reader] hit #{ikbd_reader_hits} pc={pc_before:#08x} sr={:#06x} ipl={ipl} supervisor={supervisor}",
                        cpu.sr
                    );
                }
            }

            st.tick(cycles);
            // `Cpu::step` never takes the trace exception itself (vector 9,
            // SR's T bit) — see its doc: it is the caller's responsibility
            // to check `trace_pending` and call `take_trace_exception`
            // before the next step. This binary didn't do this at all
            // until now: a program that sets T=1 (a common anti-copy/
            // anti-debugger technique — found while digging into why
            // Rick_Dangerous.stx never boots) would then keep executing
            // normally instead of triggering a trap after EVERY
            // instruction like the real silicon, quickly drifting into an
            // execution flow that has nothing to do with the real program
            // anymore.
            if cpu.trace_pending {
                cpu.take_trace_exception(&mut st);
            }
            let drive_sound_events = st.wd1772.take_sound_events();
            if !drive_sound_events.is_empty() {
                drive_sound.handle_events(&drive_sound_events);
            }
            step_count += 1;

            if watch_video {
                let base = st.shifter.video_base();
                // Lines 0-66: now includes the menu bar itself (lines
                // 0-10) in addition to the area below the menu, to spot
                // the instruction that writes the cursor/menu bar when the
                // cursor approaches it (user-reported hint: the cursor
                // turns partially yellow/red near the menu, and on
                // clicking an icon).
                let start = base;
                let len: u32 = 67 * 160;
                let mut hash: u64 = 0xcbf29ce484222325;
                for o in 0..len {
                    hash ^= st.read8(start.wrapping_add(o)) as u64;
                    hash = hash.wrapping_mul(0x100000001b3);
                }
                if watch_video_hash != Some(hash) {
                    if watch_video_hash.is_some() {
                        watch_video_hits += 1;
                        // `cpu.cycles` (and the delta since the last
                        // detected modification) lets us measure how many
                        // real CPU cycles elapse between two successive
                        // writes into this area (e.g. the 4 planes of the
                        // same cursor sprite) — to compare against the 512
                        // cycles/line of PAL to judge whether a realistic
                        // multi-plane sequence can actually straddle a line
                        // boundary (the "cursor turns yellow" question:
                        // scanline overlap during a non-atomic multi-plane
                        // update).
                        let delta = cpu.cycles.wrapping_sub(watch_video_last_cycles);
                        eprintln!(
                            "[watch] video area (lines 0-66) modified by the instruction at pc={pc_before:#08x} (change #{watch_video_hits}) cycles={} delta={delta}",
                            cpu.cycles
                        );
                    }
                    watch_video_hash = Some(hash);
                    watch_video_last_cycles = cpu.cycles;
                }
            }

            if let Some((start, end)) = watch_range {
                for (i, prev) in watch_range_snapshot.iter_mut().enumerate() {
                    let addr = start + i as u32;
                    let now = st.read8(addr);
                    if now != *prev {
                        watch_range_hits += 1;
                        eprintln!(
                            "[range] addr={addr:#08x} {:#04x}->{:#04x} pc={pc_before:#08x} (#{watch_range_hits})",
                            *prev, now
                        );
                        *prev = now;
                    }
                }
                let _ = end;
            }

            if debug && last_report.elapsed().as_secs_f64() >= 1.0 {
                eprintln!(
                    "steps={step_count} cycles={} effective_mhz={:.3} pc={:#08x} sr={:#06x} video_base={:#08x} video_counter={:#08x} phystop={:#08x} v_bas_ad={:#08x}",
                    cpu.cycles,
                    cpu.cycles as f64 / 1_000_000.0 / last_report_start.elapsed().as_secs_f64(),
                    cpu.pc,
                    cpu.sr,
                    st.shifter.video_base(),
                    st.shifter.video_counter(),
                    st.read32(0x42E),
                    st.read32(0x44E)
                );
                if dump_video {
                    let base = st.shifter.video_base();
                    eprintln!("[dump] video_base={base:#08x}");
                    for line in 0..100usize {
                        if let Some(row) = st.framebuffer.get(line) {
                            let distinct: std::collections::BTreeSet<(u8, u8, u8)> = row.iter().copied().collect();
                            // Only prints raw bytes for "interesting" lines
                            // (more than 3 colors): avoids flooding the log
                            // for lines already understood (white
                            // background/plain black or green text).
                            if distinct.len() > 3 {
                                let addr = base.wrapping_add(line as u32 * 160);
                                let bytes: Vec<u8> = (0..160).map(|o| st.read8(addr.wrapping_add(o))).collect();
                                eprintln!(
                                    "[raw] line {line:02} +{:#06x}: {}",
                                    line * 160,
                                    bytes.iter().map(|b| format!("{b:02x}")).collect::<Vec<_>>().join("")
                                );
                            }
                            eprintln!(
                                "[fb] line {line:02}: {} distinct color(s): {}",
                                distinct.len(),
                                distinct.iter().take(8).map(|(r, g, b)| format!("({r:02x},{g:02x},{b:02x})")).collect::<Vec<_>>().join(" ")
                            );
                        }
                    }
                }
                last_report = std::time::Instant::now();
            }

            audio_cycle_acc += cycles as f64;
            while audio_cycle_acc >= cycles_per_sample {
                audio_cycle_acc -= cycles_per_sample;
                let dma_lr = st.next_dma_sample(AUDIO_SAMPLE_RATE as u32);
                let ym_levels = st.ym2149.take_averaged_levels();
                let (raw_left, raw_right) = mix_sample(ym_levels, dma_lr);
                // Mechanical drive noise: mono background ambience, mixed
                // as-is into both channels (no DC filter nor Microwire
                // gain — it is a mechanically-originated noise, not a
                // signal coming from the LMC1992).
                let mut drive_sample = [0i32];
                drive_sound.mix_into(&mut drive_sample);
                let raw_left = raw_left + drive_sample[0] as f32;
                let raw_right = raw_right + drive_sample[0] as f32;
                // DC removed BEFORE the Microwire filter (an artifact of
                // our PSG mixing, not a physical phenomenon that the
                // volume/filter should scale); gain smoothed (avoids a
                // zipper-noise "click" on an abrupt volume change) then
                // injected INTO the bass/treble filter (Hatari-style,
                // `DmaSnd_IIRfilterL`/`R` — the gain applies at the
                // filter's input, not downstream, see the doc of
                // `Microwire::filter_left`).
                let dc_left = dc_blocker_left.process(raw_left);
                let dc_right = dc_blocker_right.process(raw_right);
                gain_smooth_left += (st.microwire.left_gain() - gain_smooth_left) * GAIN_SMOOTH_COEFF;
                gain_smooth_right += (st.microwire.right_gain() - gain_smooth_right) * GAIN_SMOOTH_COEFF;
                let filtered_left = st.microwire.filter_left(dc_left, gain_smooth_left);
                let filtered_right = st.microwire.filter_right(dc_right, gain_smooth_right);
                let left = filtered_left.clamp(i16::MIN as f32, i16::MAX as f32) as i16;
                let right = filtered_right.clamp(i16::MIN as f32, i16::MAX as f32) as i16;
                // Interleaved L,R,L,R... (stereo audio queue, see `desired_spec`).
                audio_buffer.push(left);
                audio_buffer.push(right);
            }

            if st.glue.frame_count() != frame_before {
                break;
            }
        }

        if !audio_buffer.is_empty() {
            let mut recording_failed = false;
            if let Some(recorder) = wav_recorder.as_mut() {
                // Before `mute`: we record the sound actually produced,
                // not silence if the user muted the host sound.
                if let Err(e) = recorder.append(&audio_buffer) {
                    eprintln!("RUST68_RECORD_WAV: write error ({e}), recording stopped");
                    recording_failed = true;
                }
            }
            if recording_failed {
                wav_recorder = None;
            }
            // `mute`: doesn't send the real sound to SDL, but keeps
            // filling the audio queue (with silence, same number of
            // samples) — it is the FILL LEVEL of this queue that paces the
            // emulation speed (see AUDIO_QUEUE_HIGH_WATERMARK above);
            // completely skipping `queue_audio` (as a previous version
            // did) left the queue permanently empty and therefore also
            // removed this pacing, running the emulation much faster than
            // real speed.
            if mute {
                audio_buffer.iter_mut().for_each(|s| *s = 0);
            }
            let _ = audio_queue.queue_audio(&audio_buffer);
            audio_buffer.clear();
        }

        if !audio_started && audio_queue.size() >= AUDIO_QUEUE_PRIME_WATERMARK {
            audio_queue.resume();
            audio_started = true;
        }

        if std::env::var("RUST68_TRACE_PALETTE").is_ok() {
            frame_count_dbg += 1;
            if frame_count_dbg % 100 == 0 {
                eprintln!("[palette] frame={frame_count_dbg} {:?}", st.shifter.palette_raw());
            }
        }
        // Resolution change (rare along the way, but possible: program
        // switch, demo): recreate the window/texture at the new integer
        // size rather than continuing to stretch the old one, which would
        // break the integer scale again ([`BorderLayout`]).
        let new_layout = BorderLayout::for_resolution(st.shifter.resolution());
        if new_layout.window_size() != current_layout.window_size() {
            let (win_w, win_h) = new_layout.window_size();
            // Only resizes the REAL window when not in fullscreen: in
            // fullscreen it is the logical size (below) that must change,
            // not the window itself (already at screen size).
            if canvas.window().fullscreen_state() == FullscreenType::Off {
                let _ = canvas.window_mut().set_size(win_w, win_h);
            }
            texture = texture_creator
                .create_texture_streaming(PixelFormatEnum::RGB24, win_w, win_h)
                .expect("texture recreation");
            let _ = canvas.set_logical_size(win_w, win_h);
            current_layout = new_layout;
        }

        render_frame(&st, &mut texture);
        canvas.clear();
        let _ = canvas.copy(&texture, None, None);
        canvas.present();

        // Real-time pacing: we sleep exactly the gap between the emulated
        // CPU time (cpu.cycles / cpu_hz) and the real time elapsed since
        // the start (`last_report_start`), so as never to emulate faster
        // than real time. Replaces the previous indirect pacing based
        // solely on audio queue fill level: the latter only corrected for
        // being AHEAD of real time (sleeping while the queue is too full),
        // never for being BEHIND — a single sleep that ran too long
        // (macOS timer coalescing / app being put to sleep, among others)
        // would then let the emulation drift behind real time with no
        // catch-up at all, draining the queue and causing an audio glitch
        // every few seconds. A direct wall-clock reference self-corrects:
        // a sleep that overshoots once only shortens the next one by the
        // same amount, with no cumulative drift — and if we're very far
        // behind (window backgrounded, debugger breakpoint...), we simply
        // don't sleep at all until we've caught up, with no abrupt
        // catch-up jolt.
        let target_elapsed = Duration::from_secs_f64(cpu.cycles as f64 / profile.cpu_hz as f64);
        let real_elapsed = last_report_start.elapsed();
        if target_elapsed > real_elapsed {
            std::thread::sleep(target_elapsed - real_elapsed);
        }

        // Safety net: also caps the audio queue itself (e.g. a host audio
        // device abnormally slow to drain it), in case the wall-clock
        // pacing above isn't sufficient on its own.
        while audio_queue.size() > AUDIO_QUEUE_HIGH_WATERMARK {
            std::thread::sleep(Duration::from_millis(5));
        }
    }
}

/// Mixes the PSG (YM2149, 3 channels, levels 0-31 already temporally
/// AVERAGED since the last sample — see [`Ym2149::take_averaged_levels`],
/// without which a high-pitched tone (chip period shorter than the audio
/// sampling period) would produce spectral aliasing sounding like a grainy
/// glitch rather than a clean tone) and the DMA Sound (STE, real
/// independent left/right samples) into a **raw** stereo sample: neither
/// Microwire gain (volume AND bass/treble) nor DC removal nor clamping —
/// see their separate application in `main` (gain smoothed to avoid a
/// zipper-noise "click", DC removed before this gain since it's an
/// artifact of this mixing, not a physical phenomenon that volume should
/// scale; bass/treble filter afterward, Hatari-style `DmaSnd_Apply_LMC` —
/// see the doc of `Microwire`).
///
/// The 3 PSG channels are combined NON-LINEARLY (Hatari-style,
/// [`mix_channels_model`], see its doc) rather than summed: the real DAC of
/// the YM2149 saturates well below 3x a single voice when several channels
/// play at full amplitude simultaneously. The result (`0.0..=65535.0`) is
/// centered and halved to leave headroom and avoid clipping once combined
/// with DMA Sound.
fn mix_sample(ym_levels: [f32; 3], dma_lr: (i8, i8)) -> (f32, f32) {
    let combined = mix_channels_model(ym_levels); // 0.0..=65535.0
    let ym_sample = (combined - 32767.5) * (i16::MAX as f32 / 32767.5) / 2.0;

    let (l, r) = dma_lr;
    // Signed 8-bit PCM samples (-128..127), scaled to about half the i16
    // range (same as for the PSG) — left and right remain SEPARATE (no
    // averaging), unlike the previous mono version.
    let dma_left = l as f32 * 128.0;
    let dma_right = r as f32 * 128.0;

    (ym_sample + dma_left, ym_sample + dma_right)
}

/// Minimal WAV recorder (16-bit stereo PCM, no external dependency) — see
/// `RUST68_RECORD_WAV` in `main`. The header is rewritten after every
/// append (negligible cost: 44 bytes, once per video frame) rather than
/// only once at closing, so the file remains a valid WAV even if the
/// process is killed abruptly (window close, Ctrl-C) without going through
/// a clean exit path.
struct WavRecorder {
    file: std::fs::File,
    data_bytes_written: u32,
}

impl WavRecorder {
    const CHANNELS: u16 = 2;
    const BITS_PER_SAMPLE: u16 = 16;

    fn create(path: &str) -> std::io::Result<Self> {
        let mut file = std::fs::File::create(path)?;
        Self::write_header(&mut file, 0)?;
        Ok(WavRecorder { file, data_bytes_written: 0 })
    }

    fn write_header(file: &mut std::fs::File, data_bytes: u32) -> std::io::Result<()> {
        use std::io::{Seek, SeekFrom, Write};
        file.seek(SeekFrom::Start(0))?;
        let sample_rate = AUDIO_SAMPLE_RATE as u32;
        let byte_rate = sample_rate * Self::CHANNELS as u32 * Self::BITS_PER_SAMPLE as u32 / 8;
        let block_align = Self::CHANNELS * Self::BITS_PER_SAMPLE / 8;
        file.write_all(b"RIFF")?;
        file.write_all(&(36 + data_bytes).to_le_bytes())?;
        file.write_all(b"WAVE")?;
        file.write_all(b"fmt ")?;
        file.write_all(&16u32.to_le_bytes())?;
        file.write_all(&1u16.to_le_bytes())?; // PCM
        file.write_all(&Self::CHANNELS.to_le_bytes())?;
        file.write_all(&sample_rate.to_le_bytes())?;
        file.write_all(&byte_rate.to_le_bytes())?;
        file.write_all(&block_align.to_le_bytes())?;
        file.write_all(&Self::BITS_PER_SAMPLE.to_le_bytes())?;
        file.write_all(b"data")?;
        file.write_all(&data_bytes.to_le_bytes())?;
        Ok(())
    }

    fn append(&mut self, samples: &[i16]) -> std::io::Result<()> {
        use std::io::{Seek, SeekFrom, Write};
        self.file.seek(SeekFrom::End(0))?;
        for s in samples {
            self.file.write_all(&s.to_le_bytes())?;
        }
        self.data_bytes_written += (samples.len() * 2) as u32;
        Self::write_header(&mut self.file, self.data_bytes_written)?;
        self.file.seek(SeekFrom::End(0))?;
        Ok(())
    }
}

/// DC blocker (one-pole high-pass filter): `y[n] = x[n] - x[n-1] + R·y[n-1]`,
/// a standard technique for removing a continuous bias from an audio
/// signal without knowing its exact cause or precise value — see the
/// comment on its usage in `main`. `R` close to 1 places the cutoff very
/// low (nearly inaudible on the useful content, only pure DC is removed).
struct DcBlocker {
    prev_x: f32,
    prev_y: f32,
}

impl DcBlocker {
    const R: f32 = 0.995;

    fn new() -> Self {
        DcBlocker { prev_x: 0.0, prev_y: 0.0 }
    }

    fn process(&mut self, x: f32) -> f32 {
        let y = x - self.prev_x + Self::R * self.prev_y;
        self.prev_x = x;
        self.prev_y = y;
        y
    }
}

/// Display geometry (active area + normal border, always present on a real
/// ST/STE monitor) for a given resolution.
///
/// On real silicon there is no dedicated border color register: this area
/// simply displays palette 0 (see [`rust68::peripherals::
/// atari_st::shifter::Shifter::border_color`]) permanently, whether a
/// border-removal trick is active or not. Dimensions measured from Hatari
/// (`conv_st.h`: `OVERSCAN_TOP`=29, `MAX_OVERSCAN_BOTTOM`=47,
/// `NUM_VISIBLE_LINE_PIXELS`=48+320+48): 29 lines at the top / 47 at the
/// bottom, 48px of border on each side in low resolution. In medium
/// resolution the horizontal pixel clock is twice as fast (640 instead of
/// 320 active pixels) so the same border duration occupies twice as many
/// pixels (96px on each side); the height doesn't change (the number of
/// lines doesn't depend on horizontal resolution). In high resolution the
/// monochrome SM124 monitor has no color overscan: no border.
///
/// `zoom_x`/`zoom_y` are the same doubling factors already used before the
/// border was added to obtain visually square pixels (2x2 in low
/// resolution, 1x2 in medium resolution — the hardware pixel there is
/// twice as tall as it is wide —, 1x1 in high resolution): applying them
/// to the border as well keeps an integer scale everywhere, rather than
/// stretching the whole border+image into a fixed-size window (which made
/// GEM text unreadable: the scale factor was then no longer an integer
/// once the border was added to a fixed 640x400 window).
struct BorderLayout {
    nominal_w: usize,
    nominal_h: usize,
    border_l: usize,
    border_r: usize,
    border_t: usize,
    border_b: usize,
    zoom_x: usize,
    zoom_y: usize,
}

impl BorderLayout {
    fn for_resolution(resolution: Resolution) -> Self {
        match resolution {
            Resolution::Low => Self {
                nominal_w: 320,
                nominal_h: 200,
                border_l: 48,
                border_r: 48,
                border_t: 29,
                border_b: 47,
                zoom_x: 2,
                zoom_y: 2,
            },
            Resolution::Medium => Self {
                nominal_w: 640,
                nominal_h: 200,
                border_l: 96,
                border_r: 96,
                border_t: 29,
                border_b: 47,
                zoom_x: 1,
                zoom_y: 2,
            },
            Resolution::High => Self {
                nominal_w: 640,
                nominal_h: 400,
                border_l: 0,
                border_r: 0,
                border_t: 0,
                border_b: 0,
                zoom_x: 1,
                zoom_y: 1,
            },
        }
    }

    fn canvas_w(&self) -> usize {
        self.nominal_w + self.border_l + self.border_r
    }

    fn canvas_h(&self) -> usize {
        self.nominal_h + self.border_t + self.border_b
    }

    /// Window/texture size needed to display this geometry at an integer
    /// scale (square pixels, no stretching).
    fn window_size(&self) -> (u32, u32) {
        (
            (self.canvas_w() * self.zoom_x) as u32,
            (self.canvas_h() * self.zoom_y) as u32,
        )
    }
}

/// Copies the board's framebuffer (one line per entry, 24-bit RGB) into
/// `texture`, with the border margin always visible on a real ST/STE
/// monitor ([`BorderLayout`]). `texture` must already be sized to
/// `BorderLayout::for_resolution(st.shifter.resolution()).window_size()`
/// (see the main loop, which recreates the texture/window on a resolution
/// change): this function simply draws at its current size, whatever it
/// may be.
fn render_frame(st: &AtariSt, texture: &mut sdl2::render::Texture) {
    let layout = BorderLayout::for_resolution(st.shifter.resolution());
    let canvas_w = layout.canvas_w();
    let canvas_h = layout.canvas_h();
    let border_color = st.shifter.border_color();

    let sdl2::render::TextureQuery { width: tex_w, height: tex_h, .. } = texture.query();
    let (tex_w, tex_h) = (tex_w as usize, tex_h as usize);

    // ACTUAL framebuffer dimensions, not the nominal resolution: STE
    // border/overscan removal (see `peripherals::atari_st::
    // glue`/`shifter`) can produce a frame with MORE lines than the
    // nominal 200 (vertical overscan, `Glue::write_sync`) and individual
    // lines WIDER than the programmed resolution (horizontal border,
    // `Shifter::write_resolution`/`write_sync`). This revealed content is
    // displayed by scaling it INTO the nominal active window (as before
    // the border margin was added above), rather than positioned
    // pixel-exact within the border area — a possible refinement but
    // independent of the normal margin added here.
    let visible_height = st.framebuffer.len().max(1);
    let src_width = st.framebuffer.iter().map(|row| row.len()).max().unwrap_or(320).max(1);

    let _ = texture.with_lock(None, |buffer: &mut [u8], pitch: usize| {
        for dst_y in 0..tex_h {
            let canvas_y = dst_y * canvas_h / tex_h;
            for dst_x in 0..tex_w {
                let canvas_x = dst_x * canvas_w / tex_w;
                let (r, g, b) = if canvas_y >= layout.border_t
                    && canvas_y < layout.border_t + layout.nominal_h
                    && canvas_x >= layout.border_l
                    && canvas_x < layout.border_l + layout.nominal_w
                {
                    let active_y = canvas_y - layout.border_t;
                    let active_x = canvas_x - layout.border_l;
                    let src_y = active_y * visible_height / layout.nominal_h;
                    let src_x = active_x * src_width / layout.nominal_w;
                    st.framebuffer
                        .get(src_y)
                        .and_then(|r| r.get(src_x))
                        .copied()
                        .unwrap_or((0, 0, 0))
                } else {
                    border_color
                };
                let offset = dst_y * pitch + dst_x * 3;
                buffer[offset] = r;
                buffer[offset + 1] = g;
                buffer[offset + 2] = b;
            }
        }
    });
}

/// Loads a floppy disk file, `.stx` (detected by its `"RSY\0"` signature),
/// `.msa` (detected by its `$0E0F` signature), or raw `.st` (geometry
/// guessed from the file size — the most common formats are tried in
/// order).
fn load_floppy(path: &str) -> Result<Box<dyn FloppyDisk>, String> {
    let data = std::fs::read(path).map_err(|e| e.to_string())?;
    if data.len() >= 4 && &data[0..4] == b"RSY\0" {
        return StxImage::parse(&data)
            .map(|img| Box::new(img) as Box<dyn FloppyDisk>)
            .map_err(|e| format!("{e:?}"));
    }
    if data.len() >= 2 && data[0] == 0x0E && data[1] == 0x0F {
        return msa::parse(&data)
            .map(|img| Box::new(img) as Box<dyn FloppyDisk>)
            .map_err(|e| format!("{e:?}"));
    }

    // Common `.st` geometries: (tracks, sides, sectors/track).
    const GEOMETRIES: &[(u8, u8, u8)] = &[
        (80, 2, 9),  // 720 KB, standard double-sided
        (80, 1, 9),  // 360 KB, standard single-sided
        (80, 2, 10), // 800 KB, extra sectors
        (82, 2, 9),  // 738 KB, extended tracks
        (80, 2, 11), // 880 KB, extra sectors
    ];
    let geometry = GEOMETRIES
        .iter()
        .find(|(t, s, spt)| {
            *t as usize * *s as usize * *spt as usize * 512 == data.len()
        })
        .copied()
        .unwrap_or_else(|| {
            eprintln!("Unrecognized .st geometry for a size of {} bytes, using a rough estimate.", data.len());
            let sectors_per_track = 9u8;
            let sides = 2u8;
            let tracks = (data.len() / (sectors_per_track as usize * sides as usize * 512)).min(255) as u8;
            (tracks, sides, sectors_per_track)
        });

    Ok(Box::new(RawDiskImage::new(
        data, geometry.0, geometry.1, geometry.2,
    )))
}

/// Loads the floppy drive's mechanical noise (motor startup, hum, step
/// click, seek hum) from a folder containing the 4 `.wav` files of the
/// Steem SSE `3rdparty/DriveSound` set (the same set used by the companion
/// project Stay). Default path: `ressources (local)/drivesound` (a local,
/// unversioned folder, see `.gitignore`), overridable via
/// `RUST68_DRIVE_SOUND_DIR`. Each missing or invalid file silently
/// degrades to a muted slot rather than preventing startup — this noise is
/// just ambience, not a required feature.
fn load_drive_sound(sample_rate: u32) -> DriveSound {
    let dir = std::env::var("RUST68_DRIVE_SOUND_DIR")
        .unwrap_or_else(|_| "ressources (local)/drivesound".to_string());
    let mut drive_sound = DriveSound::new(sample_rate);
    for (slot, filename) in [
        (Slot::Start, "drive_startup.wav"),
        (Slot::Motor, "drive_spin.wav"),
        (Slot::Step, "drive_click.wav"),
        (Slot::Seek, "drive_seek.wav"),
    ] {
        let path = format!("{dir}/{filename}");
        match std::fs::read(&path) {
            Ok(data) => match wav::load_wav_mono_i16(&data) {
                Ok((mut samples, native_rate)) => {
                    if slot == Slot::Step {
                        // `drive_click.wav` (Steem SSE 3rdparty/DriveSound
                        // set) has a long resonance tail (~200 ms total,
                        // still ~15% of peak amplitude at 80 ms) — measured
                        // by envelope analysis. On a protected track read
                        // track by track (Rick_Dangerous.stx), separate
                        // Step commands arrive every 6-7 ms: without
                        // trimming, each new click abruptly cuts off the
                        // still-strong tail of the previous one, which
                        // sounds like a continuous blur rather than a
                        // train of distinct, regular clicks. So we only
                        // keep the first ~60 ms (attack + secondary
                        // mechanical rebound around 40-55 ms), which alone
                        // is enough to make the click recognizable.
                        let keep = (native_rate as usize * 60) / 1000;
                        samples.truncate(keep);
                    }
                    drive_sound.set_sample(slot, samples, native_rate);
                }
                Err(e) => eprintln!("Floppy noise: {path} unreadable ({e}), muted slot"),
            },
            Err(e) => eprintln!("Floppy noise: {path} missing ({e}), muted slot"),
        }
    }
    drive_sound
}

