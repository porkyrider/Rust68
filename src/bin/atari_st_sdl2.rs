/// Queues one (or several) relative mouse position report(s) using the
/// IKBD protocol, over the same serial channel as the keyboard (the IKBD
/// shares a single link with the keyboard ACIA — see the module comment).
/// `dx`/`dy` are in logical ST pixels. The real IKBD firmware only encodes
/// ±15 units per packet (not ±127, the sole limit of a signed byte field)
/// — a larger movement is split into several successive packets, exactly
/// as the HD6301 really does (see `Machine::mouse_move`/`flush_input_vbl`
/// from the companion Stay project, verified against Steem SSE's
/// `ikbd_mouse_move`).
fn queue_mouse_move(ikbd: &mut rust68::peripherals::atari_st::ikbd::Ikbd, dx: i32, dy: i32, left: bool, right: bool) {
    const MAX_MOVE: i32 = 15;
    // Empirically observed (see ETAT.md): TOS swaps the two button bits
    // relative to the documented convention bit0=left/bit1=right —
    // bit0=right/bit1=left restores the correct behavior.
    let buttons = (right as u8) | ((left as u8) << 1);
    let (mut x1, mut y1) = (0i32, 0i32);
    while (dx - x1).abs() > MAX_MOVE || (dy - y1).abs() > MAX_MOVE {
        let x2 = (dx - x1).clamp(-MAX_MOVE, MAX_MOVE);
        let y2 = (dy - y1).clamp(-MAX_MOVE, MAX_MOVE);
        ikbd.mouse_move(x2 as i8, y2 as i8, buttons);
        x1 += x2;
        y1 += y2;
    }
    ikbd.mouse_move((dx - x1) as i8, (dy - y1) as i8, buttons);
}
